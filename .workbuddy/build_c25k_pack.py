def dump_box(box):
    return "[" + ",".join(("%g" % v) for v in box) + "]"


def dump_blocks(blocks):
    lines = ["{", '  "blocks": [']
    for i, b in enumerate(blocks):
        fields = [
            '      "id": %s' % json.dumps(b["id"]),
            '      "type": %s' % json.dumps(b["type"]),
            '      "registry_group": %s' % json.dumps(b["registry_group"]),
        ]
        params = b.get("params") or {}
        head = ['        "%s": %s' % (k, json.dumps(v, ensure_ascii=False))
                for k, v in params.items() if k != "aabb"]
        if "aabb" in params:
            rows = ['        "aabb": {']
            items = list(params["aabb"].items())
            for n, (key, boxes) in enumerate(items):
                body = "[" + ",".join(dump_box(x) for x in boxes) + "]"
                rows.append('          %s: %s%s' % (json.dumps(key), body,
                                                   "," if n < len(items) - 1 else ""))
            rows.append("        }")
            head.append("\n".join(rows))
        fields.append('      "params": {\n' + ",\n".join(head) + "\n      }")
        fields.append('      "block_entity": %s' % json.dumps(b["block_entity"], ensure_ascii=False))
        lines.append("    {\n" + ",\n".join(fields) + "\n    }" + ("," if i < len(blocks) - 1 else ""))
    lines.append("  ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


