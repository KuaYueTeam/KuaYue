def volume(box):
    return max(0.0, box[3] - box[0]) * max(0.0, box[4] - box[1]) * max(0.0, box[5] - box[2])


def rotate(box, deg):
    """TrainPanelShapes.rotateShape: one 90 degree step maps (x, z) to (16 - z, x)."""
    x1, y1, z1, x2, y2, z2 = box
    if deg == 90:
        return [16 - z2, y1, x1, 16 - z1, y2, x2]
    if deg == 180:
        return [16 - x2, y1, 16 - z2, 16 - x1, y2, 16 - z1]
    if deg == 270:
        return [z1, y1, 16 - x2, z2, y2, 16 - x1]
    return list(box)


def merge_boxes(boxes):
    result = [list(b) for b in boxes]
    changed = True
    while changed:
        changed = False
        for i in range(len(result)):
            for j in range(i + 1, len(result)):
                a, b = result[i], result[j]
                if not all(a[k] <= b[k + 3] + 1e-6 and b[k] <= a[k + 3] + 1e-6 for k in range(3)):
                    continue
                m = [min(a[k], b[k]) for k in range(3)] + [max(a[k + 3], b[k + 3]) for k in range(3)]
                if volume(m) <= (volume(a) + volume(b)) * (1 + MERGE_SLACK) + 1e-6:
                    result[i] = m
                    result.pop(j)
                    changed = True
                    break
            if changed:
                break
    return [[round(v, 3) for v in b] for b in result]


def north_boxes(model_path, merge=True):
    """Collision boxes of one model in the north bind pose, in block pixels."""
    boxes = []
    for box in geom.model_boxes(model_path):
        if min(box[3] - box[0], box[4] - box[1], box[5] - box[2]) < MIN_THICKNESS:
            STATS["dropped_thin"] += 1
            continue
        if volume(box) < MIN_VOLUME:
            STATS["dropped_tiny"] += 1
            continue
        boxes.append([round(v, 3) for v in box])
    return merge_boxes(boxes) if merge else sorted(boxes)


def offset_boxes(boxes, extra):
    if not any(extra):
        return boxes
    return [[round(b[0] + extra[0], 3), round(b[1] + extra[1], 3), round(b[2] + extra[2], 3),
             round(b[3] + extra[0], 3), round(b[4] + extra[1], 3), round(b[5] + extra[2], 3)]
            for b in boxes]


def rotated(boxes, deg):
    unique = []
    for box in boxes:
        candidate = [round(v, 3) for v in rotate(box, deg)]
        if candidate not in unique:
            unique.append(candidate)
    unique.sort()
    return unique


def shapes_for(closed_boxes, open_boxes, extra_yaw=0):
    """Per-facing collision, rotated by the state yaw plus the part's own yaw override."""
    shapes = {}
    for facing, deg in FACINGS:
        angle = (deg + extra_yaw) % 360
        if open_boxes is None:
            shapes["facing=" + facing] = rotated(closed_boxes, angle)
        else:
            shapes["facing=%s,open=false" % facing] = rotated(closed_boxes, angle)
            shapes["facing=%s,open=true" % facing] = rotated(open_boxes, angle)
    return shapes


def shapes_for_hinge(profiles, extra_yaw=0):
    """Collision keyed by hinge side, for parts that merged a right-hand and a left-hand model.

    `profiles` maps hinge value -> (closed_boxes, open_boxes or None). The two halves share the
    same geometry, but the keys have to exist for every hinge value the state can take.
    """
    shapes = {}
    for facing, deg in FACINGS:
        angle = (deg + extra_yaw) % 360
        for hinge, (closed_boxes, open_boxes) in profiles.items():
            if open_boxes is None:
                shapes["facing=%s,hinge=%s" % (facing, hinge)] = rotated(closed_boxes, angle)
            else:
                shapes["facing=%s,hinge=%s,open=false" % (facing, hinge)] = rotated(closed_boxes, angle)
                shapes["facing=%s,hinge=%s,open=true" % (facing, hinge)] = rotated(open_boxes, angle)
    return shapes


def shift_model(data, extra=(0.0, 0.0, 0.0)):
    """Move the authored carriage frame onto the block grid (pixels, X/Z only).

    Cubes bake ``R·(from - origin) + origin``, so from/to/origin all move together.
    Meshes bake ``R·vertex + origin``: their vertices must stay untouched, otherwise the
    offset is applied twice (and rotated) — only the pivot carries the shift.
    """
    dx, dy, dz = (MODEL_SHIFT[i] + extra[i] for i in range(3))

    def shift_point(value):
        return [round(value[0] + dx, 6), round(value[1] + dy, 6), round(value[2] + dz, 6)]

    for element in data.get("elements", []):
        is_mesh = element.get("type") == "mesh" or (
                element.get("from") is None and element.get("to") is None)
        keys = ("origin",) if is_mesh else ("from", "to", "origin")
        for key in keys:
            if element.get(key):
                element[key] = shift_point(element[key])

    def walk(nodes):
        for node in nodes:
            if isinstance(node, str):
                continue
            if node.get("origin"):
                node["origin"] = shift_point(node["origin"])
            walk(node.get("children") or [])

    walk(data.get("outliner") or [])
    for group in data.get("groups") or []:
        if group.get("origin"):
            group["origin"] = shift_point(group["origin"])
    return data


def copy_model(source_rel, suffix, extra=(0.0, 0.0, 0.0), transform=None):
    source = os.path.join(SRC, source_rel)
    data = json.load(open(source, encoding="utf-8"))
    if transform is not None:
        data = transform(data)
    data = shift_model(data, extra)
    target = os.path.join(PDIR, "models", "block", "carriage", "c25k", suffix + ".bbmodel")
    write_model(target, data)
    return source


def swing_door(data, hinge_x=0.0, angle=-90.0, hinge_z=0.375):
    """Swing a hinged door leaf 90 degrees about its vertical hinge edge.

    The leaf is turned with the element pivot/rotation instead of by moving from/to: a 90
    degree yaw about the hinge line keeps every face's UV attached to its own surface, while
    rotating the box corners alone would leave the texture on the wrong faces.
    """
    swung = json.loads(json.dumps(data))
    STATS["swung_elements"] += len(swung.get("elements", []))

    for element in swung.get("elements", []):
        if element.get("vertices"):
            raise SystemExit("door element gained mesh vertices; swing_door needs to handle them")
        if element.get("rotation") and any(abs(v) > 1e-9 for v in element["rotation"]):
            raise SystemExit("door element already rotates; swing_door would overwrite it")
        origin = element.get("origin") or [0.0, 0.0, 0.0]
        element["origin"] = [hinge_x, origin[1] if len(origin) > 1 else 0.0, hinge_z]
        element["rotation"] = [0.0, angle, 0.0]

    def walk(nodes):
        for node in nodes:
            if isinstance(node, str):
                continue
            if node.get("rotation") and any(abs(v) > 1e-9 for v in node["rotation"]):
                raise SystemExit("door group gained a rotation; swing_door needs to handle it")
            walk(node.get("children") or [])

    walk(swung.get("outliner") or [])
    return swung


def mirror_face_uvs(data):
    """Mirror a duplicated left-hand part by flipping each block face's UV rect.

    This is what the artist did for `25k通风格栅lh` (uv [0,13,16,26] -> [16,13,0,26]);
    flipping the whole texture instead would move every face onto a different part of the art.
    """
    mirrored = 0
    for element in data.get("elements", []):
        for face in (element.get("faces") or {}).values():
            uv = face.get("uv")
            if isinstance(uv, (list, tuple)) and len(uv) == 4:
                face["uv"] = [uv[2], uv[1], uv[0], uv[3]]
                mirrored += 1
    return data


